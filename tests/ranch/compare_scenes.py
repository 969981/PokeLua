#!/usr/bin/env python3
"""Compare two actual Ranch profiler TSVs: no-offer and Hayley offer.

Both input logs must be generated by tests/ranch/build_readonly_probe.py.
A zero 'found' count in offer scene fails the evidence gate.
"""
import argparse
import json
from pathlib import Path
from analyze_scan import analyze, load_rows

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--no-offer',type=Path,required=True)
    p.add_argument('--offer',type=Path,required=True)
    p.add_argument('--minimum-updates',type=int,default=600)
    p.add_argument('--out',type=Path)
    a=p.parse_args()
    if a.minimum_updates<1:p.error('minimum updates must be positive')
    no=analyze(load_rows(a.no_offer))
    yes=analyze(load_rows(a.offer))
    labels={
        'no_offer_has_no_hits':no['found']==0,
        'offer_was_observed':yes['found']>0,
        'both_scenes_long_enough':no['updates']>=a.minimum_updates and yes['updates']>=a.minimum_updates
    }
    report={
        'evidence':'REAL_DOLPHIN_PROBE_LOGS_NOT_INDEPENDENTLY_VERIFIED',
        'no_offer':{k:v for k,v in no.items() if k!='windows'},
        'offer':{k:v for k,v in yes.items() if k!='windows'},
        'gates':labels,
        'status':'REVIEW_READY' if all(labels.values()) else 'INCOMPLETE',
        'warnings':[
            'Without exact build/scene metadata and game-run logs no causal FPS claim is justified.',
            'Profiler uses instrumented onScriptUpdate; measured CPU includes its overhead.',
            'Counter read32 tracks only reads through read32Bit during scan, not all VM RAM reads.',
            'Offer event must be confirmed by in-game visual and decrypted PK4 data.'
        ]
    }
    out=json.dumps(report,indent=2,ensure_ascii=False)+'\n'
    if a.out:
        a.out.parent.mkdir(parents=True,exist_ok=True)
        a.out.write_text(out,encoding='utf-8')
        print('Wrote',a.out)
    else:print(out)
if __name__=='__main__': main()
